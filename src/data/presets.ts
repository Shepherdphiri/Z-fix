export const createInitialProject = (): Project => {
  const baseImg = SAMPLE_IMAGES[0];
  const initialLayer: Layer = {
    id: 'layer-base-1',
    name: 'Background Photo',
    type: 'image',
    visible: true,
    locked: false,
    opacity: 100,
    blendMode: 'source-over',
    imageUrl: baseImg.url,
    originalWidth: baseImg.width,
    originalHeight: baseImg.height,
    transform: {
      x: 0,
      y: 0,
      scaleX: 1,
      scaleY: 1,
      rotation: 0,
      flipH: false,
      flipV: false,
    },
    adjustments: createDefaultAdjustments(),
  };

  return {
    id: 'proj-lumina-demo-01',
    title: 'Studio Editorial Retouch',
    width: 1200,
    height: 800,
    layers: [initialLayer],
    activeLayerId: initialLayer.id,
    updatedAt: new Date().toISOString(),
    createdAt: new Date(Date.now() - 3600000 * 24).toISOString(),
    previewUrl: baseImg.url,
    syncStatus: 'synced',
  };
};
